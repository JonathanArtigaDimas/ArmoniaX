const fs = require('fs');
const path = require('path');
const pdfjsLib = require('pdfjs-dist');

const PDF_PATH = path.join(__dirname, '..', 'iResucitó-es-US.pdf');
const CANCIONERO_PATH = path.join(__dirname, '..', 'cancionero.js');
const OUTPUT_PATH = path.join(__dirname, '..', 'src', 'data', 'songMapping.ts');

function removeDiacritics(str) {
  return str.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

function normalize(text) {
  return removeDiacritics(text.toLowerCase()).trim();
}

async function main() {
  console.log('Reading PDF...');
  const pdfBuffer = new Uint8Array(fs.readFileSync(PDF_PATH));
  const doc = await pdfjsLib.getDocument({data: pdfBuffer}).promise;
  const totalPages = doc.numPages;
  console.log(`PDF has ${totalPages} pages`);

  // Build index: normalized title -> { cantoNumber, pagina }
  const index = {};

  for (let pageNum = 1; pageNum <= totalPages; pageNum++) {
    const page = await doc.getPage(pageNum);
    const content = await page.getTextContent();
    const textLines = content.items
      .map(item => item.str.trim())
      .filter(l => l.length > 0);

    if (textLines.length < 2) continue;

    // Find canto number: scan from bottom, look for 1-4 digit standalone number
    let cantoNumber = '';
    for (let i = textLines.length - 1; i >= 0; i--) {
      const line = textLines[i];
      if (line.length >= 1 && line.length <= 4 && /^\d+$/.test(line)) {
        cantoNumber = line;
        break;
      }
    }
    if (!cantoNumber) continue;

    // Title: first meaningful line (skip very short lines)
    let title = '';
    for (let i = 0; i < textLines.length; i++) {
      if (textLines[i].length > 2) {
        title = textLines[i];
        break;
      }
    }
    if (!title) continue;

    const titleNormalized = normalize(title);
    index[titleNormalized] = {
      cantoNumber: parseInt(cantoNumber, 10),
      pagina: pageNum,
      titulo: title,
    };
  }

  console.log(`Built index with ${Object.keys(index).length} entries`);

  // Load cancionero song names
  delete require.cache[require.resolve(CANCIONERO_PATH)];
  const cancionero = require(CANCIONERO_PATH);
  console.log(`Cancionero has ${cancionero.length} songs`);

  // Match songs
  const mapping = {};
  let matched = 0;
  let unmatched = 0;
  const unmatchedNames = [];

  for (const entry of cancionero) {
    const nameNormalized = normalize(entry.name);

    // Try exact match first
    if (index[nameNormalized]) {
      mapping[entry.name] = {
        cantoNumber: index[nameNormalized].cantoNumber,
        pages: [index[nameNormalized].pagina],
      };
      matched++;
      continue;
    }

    // Try substring match
    let found = false;
    for (const [key, value] of Object.entries(index)) {
      if (key.includes(nameNormalized) || nameNormalized.includes(key)) {
        mapping[entry.name] = {
          cantoNumber: value.cantoNumber,
          pages: [value.pagina],
        };
        matched++;
        found = true;
        break;
      }
    }

    if (!found) {
      unmatched++;
      unmatchedNames.push(entry.name);
    }
  }

  console.log(`Matched: ${matched}, Unmatched: ${unmatched}`);
  if (unmatchedNames.length > 0) {
    console.log('Unmatched songs:', unmatchedNames);
  }

  // Generate TypeScript file
  const output = `// Auto-generated by scripts/generateSongMapping.js
// Do not edit manually. Run: node scripts/generateSongMapping.js

export const SONG_MAPPING: Record<string, {cantoNumber: number; pages: number[]}> = ${JSON.stringify(mapping, null, 2)};
`;

  fs.writeFileSync(OUTPUT_PATH, output, 'utf8');
  console.log(`Written to ${OUTPUT_PATH}`);
}

main().catch(err => {
  console.error('Error:', err);
  process.exit(1);
});
